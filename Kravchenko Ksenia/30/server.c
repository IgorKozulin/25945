/* Лабораторная работа №30. Связь через Unix domain socket.
 *
 * Задание: два процесса общаются через локальный (Unix domain) сокет.
 * Сервер создаёт сокет и слушает его; подключившемуся клиенту он принимает
 * текст из символов верхнего и нижнего регистров, переводит его в верхний
 * регистр и печатает в свой стандартный вывод - как в задаче 25, только
 * «каналом» служит не pipe, а сокет. После разрыва соединения клиентом
 * оба процесса завершаются.
 *
 * Этот файл - сервер.
 */

#include <sys/socket.h>   /* socket, bind, listen, accept, AF_UNIX, SOCK_STREAM */
#include <sys/un.h>       /* struct sockaddr_un, sun_family, sun_path           */
#include <stdio.h>        /* perror                                            */
#include <stdlib.h>       /* exit                                              */
#include <unistd.h>       /* read, write, close, unlink                        */
#include <ctype.h>        /* toupper                                           */
#include <string.h>       /* memset, strncpy                                   */
#include <errno.h>        /* errno (в этом файле напрямую не используется)     */

/* Путь к файлу сокета: по этому имени клиент находит сервер */
#define SOCKET_PATH "my_socket"
/* Размер порции, читаемой из соединения за один read(2) */
#define BUFFER_SIZE 1024

int main() {
    int server_fd, client_fd;   /* слушающий и клиентский дескрипторы */
    struct sockaddr_un addr;    /* адрес локального сокета: семейство + путь */
    char buffer[BUFFER_SIZE];
    ssize_t num_read;

    // Создание сокета
    /* AF_UNIX - локальный сокет (имя в файловой системе, без сети),
       SOCK_STREAM - потоковый: байты идут надёжно и в том же порядке.
       Третий аргумент 0 - протокол по умолчанию для этого типа */
    server_fd = socket(AF_UNIX, SOCK_STREAM, 0);
    if (server_fd == -1) {
        perror("socket");
        exit(1);
    }

    // Привязка к пути
    /* Заполняем структуру адреса. memset обнуляет её целиком, чтобы
       sun_path гарантированно заканчивался нулевым байтом */
    memset(&addr, 0, sizeof(addr));
    addr.sun_family = AF_UNIX;
    /* Копируем путь без последнего байта: место под завершающий '\0' нужно
       оставить, иначе имя в файловой системе не будет строкой */
    strncpy(addr.sun_path, SOCKET_PATH, sizeof(addr.sun_path) - 1);

    unlink(SOCKET_PATH);  // Удалить если уже есть файл сокета с привязкой
    /* Файл сокета сам не исчезает: если прошлый запуск завершился аварийно,
       bind ниже вернул бы EADDRINUSE, поэтому старый файл удаляем заранее */

    /* bind связывает сокет с адресом - в файловой системе появляется
       файл my_socket, через который клиенты и будут подключаться */
    if (bind(server_fd, (struct sockaddr*)&addr, sizeof(addr)) == -1) {
        perror("bind");
        exit(1);
    }

    // Прослушивание
    /* listen переводит сокет в режим ожидания соединений.
       5 - длина очереди уже установленных, но ещё не принятых соединений */
    if (listen(server_fd, 5) == -1) {
        perror("listen");
        exit(1);
    }

    // Принятие клиента
    /* accept достаёт из очереди первое соединение и возвращает НОВЫЙ
       дескриптор именно для обмена данными, а server_fd продолжает слушать.
       Если очередь пуста - вызов блокирует процесс. Адрес клиента не нужен,
       поэтому второй и третий аргументы - NULL */
    client_fd = accept(server_fd, NULL, NULL);
    if (client_fd == -1) {
        perror("accept");
        exit(1);
    }

    // Чтение данных в цикле (неограниченный размер)
    /* read возвращает число прочитанных байт, 0 - клиент закрыл соединение
       (разрыв), -1 - ошибка. Читаем порциями по BUFFER_SIZE, поэтому
       объём переданного текста не ограничен */
    while ((num_read = read(client_fd, buffer, BUFFER_SIZE)) > 0) {
        /* Перевод в верхний регистр «на месте»: toupper трогает только
           строчные буквы, остальные символы оставляет как есть */
        for (ssize_t i = 0; i < num_read; i++) {
            buffer[i] = toupper(buffer[i]);
        }
        write(STDOUT_FILENO, buffer, num_read);  // Вывод в stdout
        /* Пишем ровно num_read байт: read не добавляет '\0', и в buffer
           после него лежит мусор от предыдущей порции */
    }

    /* Цикл закончился: num_read == 0 - нормальный разрыв (клиент ушёл),
       num_read == -1 - ошибка чтения, о ней и сообщаем */
    if (num_read == -1) {
        perror("read");
    }

    // Завершение
    /* Закрываем соединение с клиентом, затем слушающий сокет и удаляем
       файл сокета из файловой системы - иначе следующий запуск сервера
       не сможет выполнить bind */
    close(client_fd);
    close(server_fd);
    unlink(SOCKET_PATH);
    return 0;
}
