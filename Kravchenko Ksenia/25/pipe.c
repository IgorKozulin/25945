/* Лабораторная работа №25. Связь через программный канал (pipe).
 *
 * Задание: создать подпроцесс, который взаимодействует с родителем через
 * неименованный программный канал. Один процесс пишет в канал текст из
 * символов верхнего и нижнего регистров, второй переводит всё в верхний
 * регистр и выводит результат на терминал.
 *
 * Здесь: родитель - писатель, ребёнок - читатель и «переводчик» (toupper).
 */

#include <unistd.h>     /* pipe, fork, read, write, close, STDOUT */
#include <ctype.h>      /* toupper                                */
#include <string.h>     /* strlen                                 */
#include <stdlib.h>     /* exit                                   */
#include <sys/wait.h>   /* wait                                   */
#include <stdio.h>      /* printf                                 */

int main() {
    printf("[PROGRAM]: родитель пишет текст в pipe, дочерний переводит в uppercase и выводит.\n");

    /* pipe(fd) создаёт канал - однонаправленный буфер в ядре.
       fd[0] - конец для чтения, fd[1] - конец для записи.
       Данные, записанные в fd[1], читаются из fd[0] */
    int fd[2];
    pipe(fd);
    
    /* fork копирует процесс вместе с обоими дескрипторами канала,
       поэтому после fork у каждого процесса есть и читающий, и пишущий
       концы - лишние из них нужно закрыть */
    if (fork() == 0){

        /* ---------- Подпроцесс: читатель ---------- */
        printf("[CHILD]: читаю из pipe, перевожу в uppercase и вывожу.\n");
        /* Пишущий конец ребёнку не нужен. Если его не закрыть, read()
           никогда не увидит EOF (канал остаётся «открыт на запись») */
        close(fd[1]);
        char buf[1024];
        int n;

        /* read возвращает число прочитанных байт, 0 - конец файла
           (все пишущие концы закрыты), -1 - ошибка */
        while ((n = read(fd[0], buf, sizeof(buf))) > 0) {
            /* toupper из ctype.h переводит строчные латинские буквы
               в заглавные (остальные символы не меняет) */
            for (int i = 0; i < n; i++) buf[i] = toupper(buf[i]);
            /* write в дескриптор 1 (stdout) - вывод на терминал.
               Пишем ровно n байт: терминатор '\0' read из канала не даёт */
            write(1, buf, n);
        }

        /* Закрываем читающий конец и завершаем подпроцесс.
           exit(0) здесь нужен, чтобы ребёнок не пошёл выполнять код родителя */
        close(fd[0]);
        exit(0);

    }else{
        /* ---------- Родитель: писатель ---------- */
        char *text = "Hello iir!\n";
        /* Сначала печатаем исходный текст, чтобы было видно разницу */
        write(1, text, strlen(text));

        printf("[PARENT]: пишу текст в pipe.\n");
        /* Читающий конец родителю не нужен - закрываем его, чтобы
           остался только один пишущий конец */
        close(fd[0]);

        /* Кладём текст в канал; ребёнок прочитает его из fd[0] */
        write(fd[1], text, strlen(text));

        /* Закрытие пишущего конца - сигнал EOF для читателя:
           после этого read у ребёнка вернёт 0 и цикл закончится.
           Без этого wait(NULL) мог бы зависнуть навсегда */
        close(fd[1]);
        /* Ждём завершения подпроцесса, чтобы он успел всё допечатать */
        wait(NULL);
    }
    return 0;
}
